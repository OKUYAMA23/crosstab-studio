import json, sys

reg = json.load(open(sys.argv[1], encoding='utf-8'))
out, version = sys.argv[2], sys.argv[3]
ja = {a['id']: a for a in reg['ja']}

TYPES = [
    ('nominal', '単一回答', 'single choice without order (e.g., gender, club)'),
    ('ordinal', '順序あり', 'single choice with ordered levels (e.g., agree … disagree, grade)'),
    ('multi', '複数回答', 'multiple choice, “select all that apply”'),
    ('numeric', '数値', 'numbers (age, hours, yen)'),
    ('time', '日時', 'timestamps'),
    ('text', '使わない', 'free text; not used by most analyses (text mining uses it)'),
]


def md(s):
    return str(s).replace('|', '\\|').replace('\n', ' ').strip()


L = []
w = L.append
w(f'''# CrossTab Studio — guide for AI agents and scripts

<!-- Generated by tools/gen_agents.py from the app's analysis registry. Do not edit by hand. App version {version}. -->

CrossTab Studio is a survey-analysis app for Google Forms response CSVs (frequency tables, cross-tabulations, tests, regression, scales, figures and a written report). It runs entirely in the browser: R is executed with WebAssembly (webR), so **the data never leave the browser**.

This file explains how an AI agent or a script can drive the app and save a project file (`.prj`) and a PDF report. Everything goes through one JavaScript object, `window.CTS`, which calls the same functions as the on-screen buttons, so the numbers are identical to those produced by hand.

## What you need

- A real browser engine that runs JavaScript and WebAssembly (Chromium via Playwright, Puppeteer or Selenium; a browser-extension agent; or a person's browser). Reading the page as text is **not** enough: R only starts inside a browser.
- App URL: <https://okuyama23.github.io/crosstab-studio/>. The first load downloads about 22 MB (webR); later loads use the cache.
- Language of the screen and report: set `localStorage['cts-lang']` to `"ja"` (Japanese, default for Japanese browsers) or `"en"` **before** the page loads.
- Wait for the app with `await CTS.ready()` before anything else.

## Quick start (Playwright, Python)

```python
import asyncio, base64, json
from playwright.async_api import async_playwright

async def main():
    async with async_playwright() as p:
        browser = await p.chromium.launch()
        page = await browser.new_page()
        await page.add_init_script("localStorage.setItem('cts-lang', 'ja')")
        await page.goto("https://okuyama23.github.io/crosstab-studio/")
        await page.wait_for_function("window.CTS && CTS.ready")
        csv = open("responses.csv", encoding="utf-8-sig").read()
        spec = {{
            "csv": csv, "name": "responses.csv", "title": "部活動とおこづかいの関係",
            "columns": [{{"column": "1か月のおこづかい", "type": "ordinal"}}],
            "invalidRows": [{{"row": 201, "note": "金額が 1 億円"}}],
            "analyses": [
                {{"type": "chisq", "slots": {{"a": "部活動", "b": "1か月のおこづかい"}}}},
                {{"type": "mwu", "slots": {{"g": "部活動", "y": "1か月のおこづかい"}},
                 "choices": {{"g": {{"keep": ["運動部", "文化部"]}}}}}},
            ],
            "output": {{"prj": True, "pdf": True, "base64": True}},
        }}
        r = await page.evaluate("async (s) => {{ const r = await CTS.run(s); delete r.prj; delete r.pdf; return r; }}", spec)
        open("project.prj", "wb").write(base64.b64decode(r["prjBase64"]))
        open("report.pdf", "wb").write(base64.b64decode(r["pdfBase64"]))
        print(json.dumps(r["results"], ensure_ascii=False, indent=1))
        await browser.close()

asyncio.run(main())
```

`CTS.run` returns Blobs (`prj`, `pdf`), which cannot cross into Python, so ask for `base64: true` and delete the Blobs before returning, as above. In a browser-extension agent you can instead pass `download: true` to save the files through the browser's downloads.

## `CTS.run(spec)`

| Field | Meaning |
|---|---|
| `csv` | The response file: CSV text, a `Uint8Array`/`ArrayBuffer`, or a `Blob`/`File`. An Excel file (`.xlsx`) also works (first sheet). Omit it to keep the data already loaded. |
| `name` | File name used in the report (e.g., `"responses.csv"`). |
| `title` | Report title. |
| `columns` | Column settings applied before the analyses: `[{{ column, type, delim, label, order, scoring }}]` (see `CTS.setColumn`). |
| `invalidRows` | Rows to exclude from every analysis, the report, the Excel workbook and the R code. Row numbers start at 1 (the first response). Items are numbers or `{{ row, note }}`. |
| `flagRows` | Rows to flag (a marker only; they stay in the analyses). |
| `analyses` | List of analyses (see `CTS.addAnalysis`). The app holds at most 20 analyses. |
| `output` | `{{ prj, pdf, docx, base64, download }}`; default `{{ prj: true, pdf: true }}`. |
| `timeoutMs` | Time limit for the calculations (default 300000). |

It returns `{{ ok, version, api, rows, invalid, analyses, results, prj, pdf, docx, prjBase64, pdfBase64, docxBase64 }}`. `ok` is false when an analysis could not be calculated; its `message` says why (for example, too few responses).

## Step-by-step functions

| Function | What it does |
|---|---|
| `await CTS.ready()` | Waits until R has started and the analysis list is loaded. |
| `CTS.analyses()` | The analysis types with their slots and options (the catalogue below, in the screen language). |
| `await CTS.load(csv, name)` | Loads the responses as a new project (any open project is replaced). Returns `{{ rows, columns }}`. |
| `CTS.columns()` | The columns: `col` (number), `header` (question text), `label`, `type`, `n`, `options` (`value`, `n`) and, for numbers, `summary`. |
| `await CTS.setColumn(column, {{ type, delim, label, order, scoring }})` | Changes a column. `type` is one of the types below; `order` lists option values from top to bottom; `scoring` is `"desc"` (default: top option = highest points), `"asc"`, or `{{ mode: "custom", points: {{ value: points }} }}`. |
| `await CTS.markInvalid(rows, note)` / `CTS.unmarkInvalid(rows)` | Excludes rows from (or returns them to) all analyses. |
| `await CTS.markFlag(rows)` / `CTS.unmarkFlag(rows)` | Adds or removes flags. |
| `CTS.addAnalysis(spec)` | Adds one analysis and returns its id. |
| `CTS.removeAnalysis(id)` | Removes an analysis. |
| `await CTS.wait()` | Waits until every analysis is calculated and returns `CTS.results()`. |
| `CTS.results()` | Per analysis: `id`, `type`, `name`, `ok`, `message`, `test`, `p`, `significant`, `n`, `headline` (key values), `report` (the sentence for the report). |
| `CTS.prj()` | The project file as text (JSON). It contains the response data. |
| `await CTS.pdf()` / `await CTS.docx()` | The report as a PDF or Word Blob. |
| `CTS.reportText()` | The report as plain text. |
| `await CTS.toBase64(blobOrText)` / `CTS.download(blobOrText, name)` | Helpers for saving files. |

### Referring to columns

A column can be given as its number (`3`), its question text, or its display label. A unique beginning or a unique part of the text also works (`"部活動"`). If the text matches several columns, the call fails and lists them; then use the number. Use `CTS.columns()` to see what was detected.

### `CTS.addAnalysis(spec)`

| Field | Meaning |
|---|---|
| `type` | Analysis id from the catalogue (e.g., `"chisq"`). |
| `slots` | `{{ slotId: column }}`; for slots marked *many*, a list of columns. Each column must have one of the slot's allowed types; change the type with `setColumn` first if needed. |
| `options` | `{{ optionId: value }}` (see the catalogue). |
| `choices` | Per slot: `{{ keep: [values], drop: [values], rename: {{ value: newName }}, order: [values] }}`. Options not kept are excluded from that analysis; options renamed to the same name are merged into one group. |
| `reverse` | For scale slots: columns to reverse-score. |
| `name` | Name shown in the app and the report. |
| `figure` | Figure settings, e.g. `{{ kind: "group", orient: "v", value: "count", min: 0, max: 20000 }}`. `kind`: `stack100`, `group`, `stack`, `heat`, `bar`, `line`, `pie`, `mean`, `coef`, `box`, `scatter`, `hist`, `map`, `cloud`, `wbar`, `net` (only those that suit the analysis are used). `orient`: `"h"`/`"v"`. `value`: `"pct"`/`"count"`. Axis range: `min`, `max`, `step` (value axis) and `xMin`, `xMax`, `xStep` (scatter x axis). Size: `w`, `h`. Colours: `palette` (`gray`, `blue`, `green`, `cud`, `viridis`, …). |
| `inReport` | `false` to leave the analysis out of the report. |

## Column types

| Type | 画面での名前 | Meaning |
|---|---|---|
''')
for t, j, e in TYPES:
    w(f'| `{t}` | {j} | {e} |\n')

w('\n## Analysis catalogue\n\nSlot types say which column types each slot accepts. *many* slots take two or more columns; *optional* slots may be omitted.\n')
groups = []
for a in reg['en']:
    if a['group'] not in groups:
        groups.append(a['group'])
for g in groups:
    jg = next(ja[a['id']]['group'] for a in reg['en'] if a['group'] == g)
    w(f'\n### {md(g)}（{md(jg)}）\n')
    for a in [x for x in reg['en'] if x['group'] == g]:
        aj = ja[a['id']]
        w(f'\n#### `{a["id"]}` — {md(a["name"])}（{md(aj["name"])}）\n\n{md(a["desc"])}\n\n')
        w('| Slot | Label | 画面の名前 | Types | Many | Optional |\n|---|---|---|---|---|---|\n')
        sj = {s['id']: s for s in aj['slots']}
        for s in a['slots']:
            w(f'| `{s["id"]}` | {md(s["label"])} | {md(sj[s["id"]]["label"])} | {", ".join(s["types"])} | {"yes" if s.get("many") else ""} | {"yes" if s.get("optional") else ""} |\n')
        if a.get('opts'):
            w('\n| Option | Kind | Default | Values | Meaning |\n|---|---|---|---|---|\n')
            for o in a['opts']:
                vals = ', '.join(f'`{c["value"]}`' for c in o.get('choices') or []) or ('`true`, `false`' if o['kind'] == 'check' else '')
                w(f'| `{o["id"]}` | {o["kind"]} | `{json.dumps(o["default"], ensure_ascii=False)}` | {vals} | {md(o["label"])} |\n')

